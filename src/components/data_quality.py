"""
data_quality.py

Purpose
-------
Checks whether production data is valid and usable
before other monitoring components analyze it.

Data Quality Monitoring is different from Data Drift.

Data Quality asks:
    "Is the data valid?"

Data Drift asks:
    "Has the distribution of valid data changed?"

Responsibilities
----------------
- Validate required columns
- Detect missing values
- Validate numerical ranges
- Validate categorical values
- Detect duplicate Prediction_ID values
- Generate a data quality report

Non-Responsibilities
--------------------
- Detect Data Drift
- Monitor prediction distribution
- Calculate model performance
- Retrain the model
"""

import os
import sys
from dataclasses import dataclass

import pandas as pd

from src.exception import CustomException
from src.logger import logging

# ==========================================================
# Configuration
# ==========================================================

@dataclass
class DataQualityConfig:

    # Production data generated by the Production Logger
    production_data_path = os.path.join(
        "artifacts",
        "production_data.csv"
    )

    # Data Quality report
    quality_report_path = os.path.join(
        "artifacts",
        "data_quality_report.csv"
    )


# ==========================================================
# Data Quality Component
# ==========================================================

class DataQuality:

    def __init__(self):

        self.config = DataQualityConfig()


    def check_data_quality(self):

        """
        Perform production data quality checks.

        Returns
        -------
        DataFrame
            Data quality report.
        """

        try:

            # ==================================================
            # Read Production Data
            # ==================================================

            logging.info(
                "Reading production dataset..."
            )

            production_df = pd.read_csv(
                self.config.production_data_path
            )


            # ==================================================
            # Define Expected Schema
            # ==================================================

            required_columns = [

                "Gender",
                "Married",
                "Dependents",
                "Education",
                "Self_Employed",

                "ApplicantIncome",
                "CoapplicantIncome",
                "LoanAmount",
                "Loan_Amount_Term",
                "Credit_History",

                "Property_Area",

                "Prediction_ID",
                "Timestamp",
                "Prediction"
            ]


            # ==================================================
            # Store Quality Results
            # ==================================================

            quality_results = []


            # ==================================================
            # Schema Check
            # ==================================================

            for column in required_columns:

                exists = column in production_df.columns

                quality_results.append(
                    {
                        "Check": "Required Column",
                        "Feature": column,
                        "Status": "PASS"
                        if exists
                        else "FAIL",
                        "Details":
                            "Column exists"
                            if exists
                            else "Column is missing"
                    }
                )


            # ==================================================
            # Missing Value Checks
            # ==================================================

            for column in required_columns:

                if column not in production_df.columns:

                    continue

                missing_count = (
                    production_df[column]
                    .isna()
                    .sum()
                )

                quality_results.append(
                    {
                        "Check": "Missing Values",
                        "Feature": column,
                        "Status": "PASS"
                        if missing_count == 0
                        else "FAIL",
                        "Details":
                            f"Missing values: "
                            f"{missing_count}"
                    }
                )


            # ==================================================
            # Numerical Range Checks
            # ==================================================

            numerical_ranges = {

                "ApplicantIncome":
                    lambda x: x >= 0,

                "CoapplicantIncome":
                    lambda x: x >= 0,

                "LoanAmount":
                    lambda x: x >= 0,

                "Loan_Amount_Term":
                    lambda x: x > 0,

                "Credit_History":
                    lambda x: x.isin([0, 1])
            }


            for column, condition in (
                numerical_ranges.items()
            ):

                if column not in production_df.columns:

                    continue

                invalid_count = (
                    ~condition(
                        production_df[column]
                    )
                ).sum()

                quality_results.append(
                    {
                        "Check": "Numerical Range",
                        "Feature": column,
                        "Status": "PASS"
                        if invalid_count == 0
                        else "FAIL",
                        "Details":
                            f"Invalid values: "
                            f"{invalid_count}"
                    }
                )


            # ==================================================
            # Categorical Value Checks
            # ==========================================================

            allowed_values = {

                "Gender": [
                    "Male",
                    "Female"
                ],

                "Married": [
                    "Yes",
                    "No"
                ],

                "Dependents": [
                    "0",
                    "1",
                    "2",
                    "3+"
                ],

                "Education": [
                    "Graduate",
                    "Not Graduate"
                ],

                "Self_Employed": [
                    "Yes",
                    "No"
                ],

                "Property_Area": [
                    "Urban",
                    "Semiurban",
                    "Rural"
                ],

                "Prediction": [
                    "Y",
                    "N"
                ]
            }


            for column, allowed in (
                allowed_values.items()
            ):

                if column not in production_df.columns:

                    continue

                invalid_count = (
                    ~production_df[column]
                    .isin(allowed)
                ).sum()

                quality_results.append(
                    {
                        "Check": "Categorical Values",
                        "Feature": column,
                        "Status": "PASS"
                        if invalid_count == 0
                        else "FAIL",
                        "Details":
                            f"Invalid values: "
                            f"{invalid_count}"
                    }
                )


            # ==================================================
            # Prediction ID Uniqueness
            # ==================================================

            if "Prediction_ID" in production_df.columns:

                duplicate_count = (
                    production_df["Prediction_ID"]
                    .duplicated()
                    .sum()
                )

                quality_results.append(
                    {
                        "Check":
                            "Prediction ID Uniqueness",

                        "Feature":
                            "Prediction_ID",

                        "Status":
                            "PASS"
                            if duplicate_count == 0
                            else "FAIL",

                        "Details":
                            f"Duplicate IDs: "
                            f"{duplicate_count}"
                    }
                )


            # ==================================================
            # Convert Results to DataFrame
            # ==================================================

            quality_report = pd.DataFrame(
                quality_results
            )


            # ==================================================
            # Save Report
            # ==================================================

            quality_report.to_csv(
                self.config.quality_report_path,
                index=False
            )


            logging.info(
                "Data Quality report saved to "
                f"{self.config.quality_report_path}"
            )


            # ==================================================
            # Return Report
            # ==================================================

            return quality_report


        except Exception as e:  # noqa: BLE001

            logging.error(
                "Data Quality Monitoring failed."
            )

            raise CustomException(
                e,
                sys
            )


# ==========================================================
# Local Testing
# ==========================================================

if __name__ == "__main__":

    quality_monitor = DataQuality()

    report = quality_monitor.check_data_quality()

    print(
        "\n========== DATA QUALITY REPORT =========="
    )

    print(report)